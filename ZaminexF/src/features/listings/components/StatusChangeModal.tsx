function StatusChangeModal({ listing, onClose, onApply }: { listing: Listing; onClose: () => void; onApply: (status: string) => void; }) {
  const allowed = ["DRAFT", "ACTIVE", "PAUSED", "SOLD", "ARCHIVED"];
  const [next, setNext] = useState(allowed.includes(listing.status) ? listing.status : "ACTIVE");
  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/30 backdrop-blur-sm">
      <Card className="w-full max-w-sm p-6 shadow-2xl">
        <h3 className="text-base font-semibold mb-1">تغییر وضعیت آگهی</h3>
        <p className="text-xs text-muted-foreground mb-4">وضعیت فعلی: {toPersianListingStatus(listing.status)}</p>
        <SelectField label="وضعیت جدید" value={next} onChange={(v) => setNext(v as typeof next)} options={allowed.map((s) => ({ label: toPersianListingStatus(s), value: s }))} />
        <div className="flex gap-2 justify-end mt-4">
          <Btn variant="secondary" size="sm" onClick={onClose}>انصراف</Btn>
          <Btn variant="primary" size="sm" onClick={() => { onApply(next); onClose(); }}><Check size={13} />اعمال</Btn>
        </div>
      </Card>
    </div>
  );
}

export { StatusChangeModal };
